// Builds one idempotent SQL script that loads the normalized dataset.
//
// - The whole dataset travels as a single jsonb literal in a temp table.
// - Every write is an upsert keyed on slug / source_key; an existing row is
//   only rewritten when its content differs (`is distinct from`), so a re-run
//   changes nothing, not even updated_at.
// - Child rows no longer in the dataset are deleted (only for dataset recipes).
// - A final check raises (and rolls back everything) if row counts differ.
// Run as the table owner (supabase db query --linked, or PGlite in tests).
import { EXPECTED } from './dataset.mjs';

const TAG = '$yochef_seed$';

export function buildSeedSql(doc) {
  const payload = JSON.stringify(doc);
  if (payload.includes(TAG)) throw new Error('seed: payload contains the dollar-quote tag');

  return `-- Generated by supabase/seed/import_recipes.mjs. Do not edit by hand.
begin;

create temp table _seed (doc jsonb not null) on commit drop;
insert into _seed (doc) values (${TAG}${payload}${TAG}::jsonb);

-- recipe_sources --------------------------------------------------------------
insert into public.recipe_sources as t (source_key, title, compiler, publishers, publication_year, usage_note)
select x.source_key, x.title, x.compiler, x.publishers, x.publication_year, x.usage_note
from _seed, jsonb_to_record(doc -> 'source')
  as x(source_key text, title text, compiler text, publishers text[], publication_year int, usage_note text)
on conflict (source_key) do update set
  title = excluded.title, compiler = excluded.compiler, publishers = excluded.publishers,
  publication_year = excluded.publication_year, usage_note = excluded.usage_note
where (t.title, t.compiler, t.publishers, t.publication_year, t.usage_note)
  is distinct from (excluded.title, excluded.compiler, excluded.publishers, excluded.publication_year, excluded.usage_note);

-- categories ------------------------------------------------------------------
insert into public.categories as t (slug, name, description, sort_order)
select x.slug, x.name, x.description, x.sort_order
from _seed, jsonb_to_recordset(doc -> 'categories') as x(slug text, name text, description text, sort_order int)
on conflict (slug) do update set
  name = excluded.name, description = excluded.description, sort_order = excluded.sort_order
where (t.name, t.description, t.sort_order) is distinct from (excluded.name, excluded.description, excluded.sort_order);

-- ingredients -----------------------------------------------------------------
insert into public.ingredients as t (source_key, slug, name, aliases, common_units)
select x.source_key, x.slug, x.name, x.aliases, x.common_units
from _seed, jsonb_to_recordset(doc -> 'ingredients')
  as x(source_key text, slug text, name text, aliases text[], common_units text[])
on conflict (source_key) do update set
  slug = excluded.slug, name = excluded.name, aliases = excluded.aliases, common_units = excluded.common_units
where (t.slug, t.name, t.aliases, t.common_units)
  is distinct from (excluded.slug, excluded.name, excluded.aliases, excluded.common_units);

-- recipes ---------------------------------------------------------------------
insert into public.recipes as t (
  source_key, source_id, source_recipe_number, source_page, slug, name, description, category_id,
  difficulty, default_servings, serving_basis, serving_note, prep_time_minutes, cook_time_minutes,
  cover_image_path, status, review_issues, published_at)
select x.source_key, s.id, x.source_recipe_number, x.source_page, x.slug, x.name, x.description, c.id,
  x.difficulty, x.default_servings, x.serving_basis, x.serving_note, x.prep_time_minutes, x.cook_time_minutes,
  x.cover_image_path, x.status, x.review_issues,
  case when x.status = 'published' then now() end
from _seed
  cross join jsonb_to_recordset(_seed.doc -> 'recipes') as x(
    source_key text, source_recipe_number int, source_page int, slug text, name text, description text,
    category_slug text, difficulty text, default_servings int, serving_basis text, serving_note text,
    prep_time_minutes int, cook_time_minutes int, cover_image_path text, status text, review_issues text[])
  join public.categories c on c.slug = x.category_slug
  join public.recipe_sources s on s.source_key = (_seed.doc -> 'source' ->> 'source_key')
on conflict (source_key) do update set
  source_id = excluded.source_id, source_recipe_number = excluded.source_recipe_number,
  source_page = excluded.source_page, slug = excluded.slug, name = excluded.name,
  description = excluded.description, category_id = excluded.category_id, difficulty = excluded.difficulty,
  default_servings = excluded.default_servings, serving_basis = excluded.serving_basis,
  serving_note = excluded.serving_note, prep_time_minutes = excluded.prep_time_minutes,
  cook_time_minutes = excluded.cook_time_minutes, cover_image_path = excluded.cover_image_path,
  status = excluded.status, review_issues = excluded.review_issues,
  published_at = case when excluded.status = 'published' then coalesce(t.published_at, excluded.published_at) end
where (t.source_id, t.source_recipe_number, t.source_page, t.slug, t.name, t.description, t.category_id,
       t.difficulty, t.default_servings, t.serving_basis, t.serving_note, t.prep_time_minutes,
       t.cook_time_minutes, t.cover_image_path, t.status, t.review_issues)
  is distinct from
      (excluded.source_id, excluded.source_recipe_number, excluded.source_page, excluded.slug, excluded.name,
       excluded.description, excluded.category_id, excluded.difficulty, excluded.default_servings,
       excluded.serving_basis, excluded.serving_note, excluded.prep_time_minutes, excluded.cook_time_minutes,
       excluded.cover_image_path, excluded.status, excluded.review_issues);

-- recipe_ingredients ----------------------------------------------------------
create temp table _seed_ing on commit drop as
select rc.id as recipe_id, i.id as ingredient_id, x.sort_order, x.quantity, x.unit, x.quantity_basis,
  x.preparation_note, x.quantity_note, x.is_optional, x.ingredient_name
from _seed,
  jsonb_array_elements(doc -> 'recipes') r
  join public.recipes rc on rc.source_key = r ->> 'source_key'
  cross join jsonb_to_recordset(r -> 'ingredients') as x(
    sort_order int, ingredient_name text, quantity numeric, unit text, quantity_basis text,
    preparation_note text, quantity_note text, is_optional boolean)
  left join public.ingredients i on i.name = x.ingredient_name;

do $$
declare v_missing text;
begin
  select string_agg(distinct ingredient_name, ', ') into v_missing from _seed_ing where ingredient_id is null;
  if v_missing is not null then
    raise exception 'seed: ingredients not found: %', v_missing;
  end if;
end $$;

insert into public.recipe_ingredients as t (
  recipe_id, ingredient_id, sort_order, quantity, unit, quantity_basis, preparation_note, quantity_note, is_optional)
select recipe_id, ingredient_id, sort_order, quantity, unit, quantity_basis, preparation_note, quantity_note, is_optional
from _seed_ing
on conflict (recipe_id, sort_order) do update set
  ingredient_id = excluded.ingredient_id, quantity = excluded.quantity, unit = excluded.unit,
  quantity_basis = excluded.quantity_basis, preparation_note = excluded.preparation_note,
  quantity_note = excluded.quantity_note, is_optional = excluded.is_optional
where (t.ingredient_id, t.quantity, t.unit, t.quantity_basis, t.preparation_note, t.quantity_note, t.is_optional)
  is distinct from (excluded.ingredient_id, excluded.quantity, excluded.unit, excluded.quantity_basis,
                    excluded.preparation_note, excluded.quantity_note, excluded.is_optional);

delete from public.recipe_ingredients t
where t.recipe_id in (select distinct recipe_id from _seed_ing)
  and not exists (select 1 from _seed_ing s where s.recipe_id = t.recipe_id and s.sort_order = t.sort_order);

-- recipe_steps ----------------------------------------------------------------
create temp table _seed_steps on commit drop as
select rc.id as recipe_id, x.step_number, x.instruction, x.duration_seconds, x.duration_basis, x.timer_enabled
from _seed,
  jsonb_array_elements(doc -> 'recipes') r
  join public.recipes rc on rc.source_key = r ->> 'source_key'
  cross join jsonb_to_recordset(r -> 'steps') as x(
    step_number int, instruction text, duration_seconds int, duration_basis text, timer_enabled boolean);

insert into public.recipe_steps as t (recipe_id, step_number, instruction, duration_seconds, duration_basis, timer_enabled)
select recipe_id, step_number, instruction, duration_seconds, duration_basis, timer_enabled
from _seed_steps
on conflict (recipe_id, step_number) do update set
  instruction = excluded.instruction, duration_seconds = excluded.duration_seconds,
  duration_basis = excluded.duration_basis, timer_enabled = excluded.timer_enabled
where (t.instruction, t.duration_seconds, t.duration_basis, t.timer_enabled)
  is distinct from (excluded.instruction, excluded.duration_seconds, excluded.duration_basis, excluded.timer_enabled);

delete from public.recipe_steps t
where t.recipe_id in (select distinct recipe_id from _seed_steps)
  and not exists (select 1 from _seed_steps s where s.recipe_id = t.recipe_id and s.step_number = t.step_number);

-- verification: any mismatch aborts the whole transaction ----------------------
do $$
declare
  v_recipes int; v_published int; v_staged int; v_categories int; v_ingredients int;
  v_ri int; v_to_taste int; v_steps int; v_timers int; v_null_dur int; v_covers int;
begin
  select count(*), count(*) filter (where status = 'published'), count(*) filter (where status = 'staged'),
         count(cover_image_path)
    into v_recipes, v_published, v_staged, v_covers
    from public.recipes where source_id = (select id from public.recipe_sources where source_key = 'dieu-thao-2014');
  select count(*) into v_categories from public.categories c
    where c.slug in (select e ->> 'slug' from _seed, jsonb_array_elements(doc -> 'categories') e);
  select count(*) into v_ingredients from public.ingredients where source_key is not null;
  select count(*), count(*) filter (where quantity is null) into v_ri, v_to_taste
    from public.recipe_ingredients where recipe_id in (select recipe_id from _seed_ing);
  select count(*), count(*) filter (where timer_enabled), count(*) filter (where duration_seconds is null)
    into v_steps, v_timers, v_null_dur
    from public.recipe_steps where recipe_id in (select recipe_id from _seed_steps);

  if (v_recipes, v_published, v_staged, v_categories, v_ingredients, v_ri, v_to_taste, v_steps, v_timers, v_null_dur, v_covers)
     is distinct from
     (${EXPECTED.recipes}, ${EXPECTED.published}, ${EXPECTED.staged}, ${EXPECTED.categories}, ${EXPECTED.ingredients},
      ${EXPECTED.recipeIngredients}, ${EXPECTED.toTaste}, ${EXPECTED.steps}, ${EXPECTED.timers}, ${EXPECTED.nullDurations}, ${EXPECTED.covers}) then
    raise exception 'seed: count check failed: recipes=% published=% staged=% categories=% ingredients=% recipe_ingredients=% to_taste=% steps=% timers=% null_durations=% covers=%',
      v_recipes, v_published, v_staged, v_categories, v_ingredients, v_ri, v_to_taste, v_steps, v_timers, v_null_dur, v_covers;
  end if;
end $$;

commit;
`;
}
